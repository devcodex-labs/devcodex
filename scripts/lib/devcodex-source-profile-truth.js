'use strict'

// ProfileCurrentTruthV1 for the DevCodex source repository itself.
// scripts/validate-profile.js enforces ProfileCurrentTruthGate when the target
// is the DevCodex package root. A generated draft therefore needs a truth record
// built from *observed* facts: package.json, local git HEAD, the local
// validation candidate identity, CI matrix from the workflow, and public GitHub
// release/workflow-run receipts. Nothing is assumed: missing evidence stays
// UNVERIFIED and the unchanged validator rejects it.

const fs = require('fs')
const path = require('path')
const { execFileSync, spawnSync } = require('child_process')
const {
  PROFILE_CURRENT_TRUTH_REF,
  extractWorkflowCurrentTruth
} = require('./profile-current-truth')

const PACKAGE_ROOT = path.resolve(__dirname, '..', '..')
const DEFAULT_REPO = 'devcodex-labs/devcodex'

function isDevCodexSourceRoot (projectRoot) {
  return path.resolve(projectRoot || '') === PACKAGE_ROOT
}

function isoNow () {
  return new Date().toISOString().replace(/\.\d{3}Z$/, 'Z')
}

function gitHead (root) {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
  } catch { return '' }
}

const FETCH_SCRIPT = `
const [repo, tag] = process.argv.slice(1)
const headers = { 'user-agent': 'devcodex-profile-truth', accept: 'application/vnd.github+json' }
if (process.env.GITHUB_TOKEN) headers.authorization = 'Bearer ' + process.env.GITHUB_TOKEN
const get = async url => { const r = await fetch(url, { headers }); if (!r.ok) throw new Error(url + ' ' + r.status); return r.json() }
;(async () => {
  const out = {}
  try { out.release = await get('https://api.github.com/repos/' + repo + '/releases/tags/' + tag) } catch (e) { out.releaseError = e.message }
  try {
    const runs = await get('https://api.github.com/repos/' + repo + '/actions/workflows/publish.yml/runs?per_page=30')
    out.publish = (runs.workflow_runs || []).find(r => r.head_branch === tag && r.event === 'push') || null
  } catch (e) { out.publishError = e.message }
  if (out.publish && out.publish.head_sha) {
    try {
      const runs = await get('https://api.github.com/repos/' + repo + '/actions/workflows/ci.yml/runs?per_page=10&head_sha=' + out.publish.head_sha)
      out.ci = (runs.workflow_runs || [])[0] || null
    } catch (e) { out.ciError = e.message }
  }
  process.stdout.write(JSON.stringify(out))
})()
`

function fetchReleaseEvidence (repo, tag, options = {}) {
  if (options.evidence) return options.evidence
  const result = spawnSync(process.execPath, ['-e', FETCH_SCRIPT, repo, tag], {
    encoding: 'utf8', timeout: options.timeoutMs || 20000, env: process.env
  })
  try { return JSON.parse(result.stdout || '{}') } catch { return {} }
}

function observed (identityField, identity, status, at) {
  return { [identityField]: String(identity || 'unobserved'), status, observedAt: at }
}

function runStatus (run) {
  if (!run) return 'UNVERIFIED'
  if (run.status !== 'completed') return 'UNVERIFIED'
  return run.conclusion === 'success' ? 'PASS' : 'BLOCK'
}

function buildDevCodexSourceTruthRecord (projectRoot, options = {}) {
  const root = path.resolve(projectRoot)
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
  const version = pkg.version
  const tag = `v${version}`
  const head = options.gitHead || gitHead(root)
  const now = options.now || isoNow()
  let candidateId = options.candidateId || ''
  if (!candidateId) {
    try { candidateId = require('./validation-dag').buildCandidateIdentity({ repoRoot: root }).candidateId } catch { }
  }
  const evidence = fetchReleaseEvidence(options.repo || DEFAULT_REPO, tag, options)
  const release = evidence.release || null
  const publish = evidence.publish || null
  const ci = evidence.ci || null
  const releaseCommit = /^[0-9a-f]{40}$/i.test(String(publish?.head_sha || '')) ? publish.head_sha : head
  const readText = file => { try { return fs.readFileSync(path.join(root, file), 'utf8') } catch { return '' } }
  let manifest = null
  try { manifest = JSON.parse(readText('scripts/validation-manifest.json') || 'null') } catch { }
  return {
    schemaVersion: 'ProfileCurrentTruthV1',
    sourceVersion: version,
    releaseState: 'working-source (generated by devcodex profile init from observed release receipts)',
    npmLatest: version,
    gitHead: head,
    releaseCommit,
    sourceCandidate: {
      schemaVersion: 'SourceCandidateTruthV1',
      candidateId,
      status: 'LOCAL_PENDING',
      localQualification: observed('runId', 'not-run', 'UNVERIFIED', now),
      remoteCi: { ...observed('runId', 'not-run', 'UNVERIFIED', now), head },
      releaseAuthorized: false
    },
    ciRun: { ...observed('id', ci?.id, runStatus(ci), now), ...(ci?.head_sha ? { head: ci.head_sha } : {}) },
    publishRun: { ...observed('id', publish?.id, runStatus(publish), now), ...(publish?.head_sha ? { head: publish.head_sha } : {}) },
    githubRelease: observed('tag', release?.tag_name || tag, release && !release.draft ? 'PASS' : 'UNVERIFIED', now),
    ciMatrix: extractWorkflowCurrentTruth(readText('.github/workflows/ci.yml'), manifest),
    asOf: now
  }
}

function truthSection (record) {
  return ['## ProfileCurrentTruthV1', '```json', JSON.stringify(record, null, 2), '```', ''].join('\n')
}

function withTruthRef (text, title) {
  const body = String(text || `# ${title}\n`)
  if (body.includes(PROFILE_CURRENT_TRUTH_REF)) return body
  return `${body.replace(/\s*$/, '\n')}\n> 当前发布真相：${PROFILE_CURRENT_TRUTH_REF}\n`
}

/** Add the release-truth carrier and references required for the DevCodex source Profile. */
function augmentDevCodexSourceProfileContents (contents, projectRoot, options = {}) {
  if (!isDevCodexSourceRoot(projectRoot)) return contents
  const next = { ...contents }
  const record = buildDevCodexSourceTruthRecord(projectRoot, options)
  const release = String(next['05-发布规范.md'] || '# 05 发布规范\n')
  next['05-发布规范.md'] = /^## ProfileCurrentTruthV1/m.test(release)
    ? release
    : `${release.replace(/\s*$/, '\n')}\n${truthSection(record)}`
  next['01-项目信息.md'] = withTruthRef(next['01-项目信息.md'], '01 项目信息')
  next['04-测试规范.md'] = withTruthRef(next['04-测试规范.md'], '04 测试规范')
  next['07-用户文档与契约规范.md'] = withTruthRef(next['07-用户文档与契约规范.md'], '07 用户文档与契约规范')
  return next
}

module.exports = {
  augmentDevCodexSourceProfileContents,
  buildDevCodexSourceTruthRecord,
  isDevCodexSourceRoot
}
