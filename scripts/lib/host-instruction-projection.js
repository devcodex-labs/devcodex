'use strict'

const crypto = require('crypto')

function stableValue(value) {
  if (Array.isArray(value)) return value.map(stableValue)
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.keys(value).sort().map(key => [key, stableValue(value[key])]))
  }
  return value
}

function digest(value) {
  const body = Buffer.isBuffer(value) || typeof value === 'string'
    ? value
    : JSON.stringify(stableValue(value))
  return crypto.createHash('sha256').update(body).digest('hex')
}

function cleanCell(value) {
  return String(value || '').trim().replace(/\*\*/g, '')
}

function parseMandatoryRules(source) {
  const rules = new Map()
  const duplicates = []
  for (const line of String(source || '').split(/\r?\n/)) {
    const match = line.match(/^\|\s*([SC]\d{2})\s*\|\s*([^|]+)\|\s*([^|]+)\|/)
    if (!match) continue
    const [, id, first, second] = match
    if (rules.has(id)) duplicates.push(id)
    const text = id.startsWith('S')
      ? cleanCell(first)
      : `${cleanCell(first)}：${cleanCell(second)}`
    rules.set(id, { id, text })
  }
  return { rules, duplicates: Array.from(new Set(duplicates)).sort() }
}

function textMetrics(content) {
  const normalized = String(content || '')
  return {
    bytes: Buffer.byteLength(normalized, 'utf8'),
    lines: normalized ? normalized.split(/\r?\n/).length : 0,
    digest: digest(normalized)
  }
}

function detectContentCollisions(files) {
  const groups = new Map()
  for (const [name, content] of Object.entries(files || {})) {
    if (!name.toLowerCase().endsWith('.md')) continue
    const metrics = textMetrics(content)
    if (!groups.has(metrics.digest)) groups.set(metrics.digest, [])
    groups.get(metrics.digest).push(name)
  }
  return Array.from(groups.entries())
    .filter(([, names]) => names.length > 1)
    .map(([contentDigest, names]) => ({ contentDigest, paths: names.sort() }))
    .sort((left, right) => left.contentDigest.localeCompare(right.contentDigest))
}

function sourceRuleLines(parsed, ids, errors) {
  return ids.map(id => {
    const rule = parsed.rules.get(id)
    if (!rule) {
      errors.push(`mandatory-rule-missing:${id}`)
      return `- ${id}：[FULL FALLBACK REQUIRED]`
    }
    return `- ${id}：${rule.text}`
  })
}

function validateConfig(config, errors) {
  if (config?.schemaVersion !== 'HostInstructionProjectionConfigV1') errors.push('config-schema-invalid')
  if (!Array.isArray(config?.mandatoryRuleIds) || !config.mandatoryRuleIds.length) errors.push('mandatory-rules-invalid')
  if (new Set(config?.mandatoryRuleIds || []).size !== (config?.mandatoryRuleIds || []).length) errors.push('mandatory-rules-duplicate')
  if (!Array.isArray(config?.semanticGroups) || !config.semanticGroups.length) errors.push('semantic-groups-invalid')
  const requiredGroups = ['routing', 'cp', 'context', 'governance', 'closure']
  const groupIds = new Set((config?.semanticGroups || []).map(group => group.id))
  for (const id of requiredGroups) if (!groupIds.has(id)) errors.push(`semantic-group-missing:${id}`)
  for (const field of ['kernelMaxBytes', 'kernelMaxLines', 'wrapperMaxBytes']) {
    if (!Number.isInteger(config?.budgets?.[field]) || config.budgets[field] <= 0) errors.push(`budget-invalid:${field}`)
  }
}

function validateSemanticGroups(source, groups, errors) {
  const coverage = []
  for (const group of groups || []) {
    const missingSourceAnchors = (group.sourceAnchors || []).filter(anchor => !source.includes(anchor))
    const projectionText = (group.projectionLines || []).join('\n')
    const missingProjectionAnchors = (group.projectionAnchors || []).filter(anchor => !projectionText.includes(anchor))
    if (!group.id || !group.title || !(group.projectionLines || []).length) errors.push(`semantic-group-invalid:${group.id || 'unknown'}`)
    for (const anchor of missingSourceAnchors) errors.push(`source-anchor-missing:${group.id}:${anchor}`)
    for (const anchor of missingProjectionAnchors) errors.push(`projection-anchor-missing:${group.id}:${anchor}`)
    coverage.push({
      id: group.id,
      sourceAnchors: group.sourceAnchors || [],
      projectionAnchors: group.projectionAnchors || [],
      missingSourceAnchors,
      missingProjectionAnchors,
      covered: missingSourceAnchors.length === 0 && missingProjectionAnchors.length === 0
    })
  }
  return coverage
}

function buildKernel({ title, hostNote, sourceDigest, configDigest, fallback, ruleLines, semanticGroups }) {
  const lines = [
    `# ${title}`,
    '',
    '> Generated from the unified DevCodex instructions source. Do not edit this file directly.',
    `> sourceDigest: ${sourceDigest}`,
    `> configDigest: ${configDigest}`,
    `> Full fallback: ${fallback}`,
    `> Host surface: ${hostNote}`,
    '',
    '## 强制不变量（S01~S07 / C01~C22）',
    '',
    ...ruleLines
  ]
  for (const group of semanticGroups) {
    lines.push('', `## ${group.title}`, '', ...group.projectionLines)
  }
  lines.push(
    '',
    '## 按需扩展与故障回退',
    '',
    '- 先按意图读取对应 Skill；不得为普通动作全量读取 Profile、记忆或完整规范。',
    `- 任一规则缺失、低置信、审计/迁移需要全量，或 coverage/freshness 失败时读取 \`${fallback}\`。`,
    '- 宿主能力、Hook 强制性与链接能力只按当前 direct evidence 声明；无证据保持 UNVERIFIED。',
    ''
  )
  return lines.join('\n')
}

function createProjectionBundle({ source, config }) {
  const errors = []
  validateConfig(config, errors)
  const sourceText = String(source || '')
  const sourceDigest = digest(sourceText)
  const configDigest = digest(config || {})
  const parsed = parseMandatoryRules(sourceText)
  for (const id of parsed.duplicates) errors.push(`mandatory-rule-duplicate:${id}`)
  const ids = Array.isArray(config?.mandatoryRuleIds) ? config.mandatoryRuleIds : []
  const ruleLines = sourceRuleLines(parsed, ids, errors)
  const semanticCoverage = validateSemanticGroups(sourceText, config?.semanticGroups || [], errors)
  const fallback = config?.fullFallbackDestination || 'user://agents/devcodex/instructions.full.md'
  const sharedKernel = buildKernel({
    title: 'DevCodex — Shared Host Kernel（generated）',
    hostNote: 'Codex / Claude import / Gemini import / Grok native AGENTS.md',
    sourceDigest,
    configDigest,
    fallback,
    ruleLines,
    semanticGroups: config?.semanticGroups || []
  })
  const copilotKernel = buildKernel({
    title: 'DevCodex — Copilot Host Kernel（generated）',
    hostNote: 'GitHub Copilot CLI user-global instructions; Hooks/MCP/Skills are deployed separately',
    sourceDigest,
    configDigest,
    fallback,
    ruleLines,
    semanticGroups: config?.semanticGroups || []
  })
  const files = {
    [config?.outputs?.sharedKernel || 'host-projections/AGENTS.md']: sharedKernel,
    [config?.outputs?.copilotKernel || 'host-projections/copilot-instructions.md']: copilotKernel,
    [config?.outputs?.claudeWrapper || 'host-projections/CLAUDE.md']: `${(config?.wrappers?.claude || []).join('\n')}\n`,
    [config?.outputs?.geminiWrapper || 'host-projections/GEMINI.md']: `${(config?.wrappers?.gemini || []).join('\n')}\n`
  }
  const outputMetrics = Object.fromEntries(Object.entries(files).map(([name, content]) => [name, textMetrics(content)]))
  const kernelNames = [config?.outputs?.sharedKernel, config?.outputs?.copilotKernel].filter(Boolean)
  for (const name of kernelNames) {
    const metrics = outputMetrics[name]
    if (!metrics) errors.push(`kernel-output-missing:${name}`)
    else {
      if (metrics.bytes > config.budgets.kernelMaxBytes) errors.push(`kernel-byte-budget-exceeded:${name}`)
      if (metrics.lines > config.budgets.kernelMaxLines) errors.push(`kernel-line-budget-exceeded:${name}`)
    }
  }
  for (const name of [config?.outputs?.claudeWrapper, config?.outputs?.geminiWrapper].filter(Boolean)) {
    const metrics = outputMetrics[name]
    if (!metrics || metrics.bytes > config.budgets.wrapperMaxBytes) errors.push(`wrapper-budget-exceeded:${name}`)
    if (metrics && !files[name].includes('@devcodex/runtime/AGENTS.md')) errors.push(`wrapper-shared-kernel-pointer-missing:${name}`)
  }
  const collisions = detectContentCollisions(files)
  for (const collision of collisions) errors.push(`complete-content-collision:${collision.paths.join(',')}`)
  const ruleCoverage = ids.map(id => ({ id, covered: parsed.rules.has(id) && !parsed.duplicates.includes(id) }))
  const coveredCount = ruleCoverage.filter(item => item.covered).length + semanticCoverage.filter(item => item.covered).length
  const mandatoryCount = ruleCoverage.length + semanticCoverage.length
  const coveragePercentage = mandatoryCount ? Number((coveredCount / mandatoryCount * 100).toFixed(2)) : 0
  if (coveragePercentage !== 100) errors.push(`mandatory-coverage-incomplete:${coveragePercentage}`)
  const mode = errors.length ? 'full-fallback' : 'kernel'
  const receiptCore = {
    schemaVersion: 'HostInstructionCoverageReceiptV1',
    sourceFile: config?.sourceFile || 'instructions.md',
    sourceDigest,
    configDigest,
    mode,
    fallback: { destination: fallback, sourceDigest, available: sourceText.length > 0 },
    budgets: config?.budgets || {},
    ruleCoverage,
    semanticCoverage,
    coverage: { coveredCount, mandatoryCount, percentage: coveragePercentage },
    outputs: outputMetrics,
    collisions,
    validation: { valid: errors.length === 0, errors }
  }
  const receipt = { ...receiptCore, receiptId: `host-instruction-coverage-${digest(receiptCore)}` }
  files[config?.outputs?.coverageReceipt || 'host-projections/coverage.json'] = `${JSON.stringify(receipt, null, 2)}\n`
  return { files, receipt }
}

module.exports = {
  createProjectionBundle,
  detectContentCollisions,
  digest,
  parseMandatoryRules,
  textMetrics
}
